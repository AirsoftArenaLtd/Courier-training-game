#!/usr/bin/env node
/*
 * The credits for the 3D asset packs (board task B-28), built from assets/3d/manifest.json and each pack's SOURCE.md
 * ("# <name>", "Author: <who>. Licence: <licence>.", "Source: <url>"), so a new pack is credited by running this again:
 *
 *   node test/tools/credits.js          writes data/credits.js and the "Credits" part of docs/ASSETS.md
 *   node test/tools/credits.js --check  exits 1 when either is out of date (test/credits.js runs it)
 *
 * CC0 asks for no credit; the game says thank you anyway (the title screen's Credits button).
 */
'use strict';
const fs = require('fs'), path = require('path');

const ROOT = path.join(__dirname, '..', '..');
const DIR = path.join(ROOT, 'assets', '3d');
const DATA = path.join(ROOT, 'data', 'credits.js');
const DOC = path.join(ROOT, 'docs', 'ASSETS.md');
const START = '<!-- credits: generated by node test/tools/credits.js -->', END = '<!-- /credits -->';

/** The packs the game ships, in manifest order, with what their SOURCE.md says. */
function packs() {
  const manifest = JSON.parse(fs.readFileSync(path.join(DIR, 'manifest.json'), 'utf8'));
  const ids = [...new Set((manifest.files || []).map(f => f.pack || f.path.split('/')[0]))];
  return ids.map(id => {
    // the notes are written by hand: bold markers go, and the licence and address are found in either usual wording
    const src = fs.readFileSync(path.join(DIR, id, 'SOURCE.md'), 'utf8').replace(/\*\*/g, '');
    const field = (re) => { const m = re.exec(src); return m ? m[1].trim().replace(/[.,]$/, '') : ''; };
    return {
      pack: id,
      name: field(/^#\s+(.+)$/m) || id,
      author: field(/^Author:\s*([^.\n]+)/m),
      licence: field(/Licen[cs]e:\s*([^.\n]+)/m) || field(/licen[cs]ed\s+(CC0[^\s.,]*)/i),
      url: field(/^Source:\s*(\S+)/m) || field(/(https?:\/\/\S+)/)
    };
  });
}

function dataFile(list) {
  return '/* The 3D asset packs and who made them (generated by node test/tools/credits.js from assets/3d; do not edit). */\n' +
    'window.OTR_DATA = window.OTR_DATA || {};\n' +
    'OTR_DATA.credits = ' + JSON.stringify(list, null, 1).replace(/^ +/gm, '') + ';\n';
}

function docPart(list) {
  return [START, '', '| Pack | Author | Licence | Source |', '| --- | --- | --- | --- |',
    ...list.map(c => `| ${c.name} (\`${c.pack}\`) | ${c.author} | ${c.licence} | ${c.url} |`), '', END].join('\n');
}

function docFile(list) {
  const doc = fs.readFileSync(DOC, 'utf8'), part = docPart(list);
  const a = doc.indexOf(START), b = doc.indexOf(END);
  if (a >= 0 && b > a) return doc.slice(0, a) + part + doc.slice(b + END.length);
  return doc.replace(/\s*$/, '') + '\n\n## Credits\n\nThe packs the game ships, with thanks (the game lists them on the title screen under Credits).\n\n' + part + '\n';
}

module.exports = { packs, dataFile, docFile };

if (require.main === module) {
  const list = packs(), want = [[DATA, dataFile(list)], [DOC, docFile(list)]];
  if (process.argv.includes('--check')) {
    const stale = want.filter(([f, text]) => !fs.existsSync(f) || fs.readFileSync(f, 'utf8') !== text).map(([f]) => path.relative(ROOT, f));
    if (stale.length) { console.error('out of date: ' + stale.join(', ') + ' (run node test/tools/credits.js)'); process.exit(1); }
    console.log(`credits up to date: ${list.length} packs`);
  } else {
    want.forEach(([f, text]) => fs.writeFileSync(f, text));
    console.log(`wrote data/credits.js and docs/ASSETS.md: ${list.length} packs`);
  }
}
